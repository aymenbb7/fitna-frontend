/**
 * Cross-browser safe clipboard copying.
 * Works on modern browsers (navigator.clipboard) and falls back to
 * document.execCommand('copy') on older iOS Safari, Android WebViews,
 * or contexts without clipboard API permissions.
 */
export async function copyToClipboard(text) {
  if (!text) return false;

  // Modern async clipboard API
  if (navigator?.clipboard?.writeText) {
    try {
      await navigator.clipboard.writeText(text);
      return true;
    } catch {
      // Fall through to fallback
    }
  }

  // Fallback using temporary textarea
  try {
    const textArea = document.createElement('textarea');
    textArea.value = text;
    // Avoid scrolling to bottom
    textArea.style.top = '0';
    textArea.style.left = '0';
    textArea.style.position = 'fixed';
    textArea.style.opacity = '0';
    textArea.style.pointerEvents = 'none';

    document.body.appendChild(textArea);
    textArea.focus();
    textArea.select();

    const successful = document.execCommand('copy');
    document.body.removeChild(textArea);
    return successful;
  } catch {
    return false;
  }
}
